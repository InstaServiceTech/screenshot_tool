_OPEN_ENDPOINTS = {"login", "login_post", "static"}


@app.before_request
def _require_login():
    if request.endpoint in _OPEN_ENDPOINTS or request.endpoint is None:
        return None
    if not session.get("user"):
        return redirect(url_for("login", next=request.path))
    return None


@app.context_processor
def _inject_user():
    return {"current_user": current_user()}


def _run_dir(run_id: str) -> str:
    d = os.path.join(RUNS_DIR, secure_filename(run_id))
    if not os.path.isdir(d):
        abort(404)
    return d


def _client_ip() -> str:
    fwd = (request.headers.get("X-Forwarded-For") or "").split(",")[0].strip()
    return fwd or (request.remote_addr or "")


def _append_audit(payload: dict) -> None:
    path = os.path.join(RUNS_DIR, "audit.jsonl")
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(payload, ensure_ascii=False) + "\n")


def _write_meta(rd: str, run_id: str, **fields) -> None:
    payload = {
        "run_id": run_id,
        "user": current_user() or "unknown",
        "created_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "ip": _client_ip(),
        **fields,
    }
    with open(os.path.join(rd, "meta.json"), "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)
    with open(os.path.join(rd, "GENERATED_BY.txt"), "w", encoding="utf-8") as f:
        f.write(f"Generated by: {payload['user']}\n")
        f.write(f"Generated at: {payload['created_at']}\n")
        if payload.get("kind"):
            f.write(f"Type: {payload['kind']}\n")
        if payload.get("count") is not None:
            f.write(f"Screenshots: {payload['count']}\n")
        if payload.get("ip"):
            f.write(f"IP: {payload['ip']}\n")
    _append_audit(payload)


def _read_meta(rd: str) -> dict:
    path = os.path.join(rd, "meta.json")
    if not os.path.isfile(path):
        return {}
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def _zip_folder(src_folder: str, zip_path: str, extra_files: list[tuple[str, str]] | None = None) -> None:
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, _dirs, files in os.walk(src_folder):
            for name in files:
                fp = os.path.join(root, name)
                arc = os.path.relpath(fp, os.path.dirname(src_folder))
                zf.write(fp, arc)
        for arc, fp in extra_files or []:
            if os.path.isfile(fp):
                zf.write(fp, arc)


# ── Auth ─────────────────────────────────────────────────────────────────────
@app.get("/login")
def login():
    if session.get("user"):
        return redirect(url_for("index"))
    nxt = request.args.get("next") or url_for("index")
    return render_template("login.html", next=nxt, error=None)


@app.post("/login")
def login_post():
    username = request.form.get("username", "")
    password = request.form.get("password", "")
    nxt = request.form.get("next") or url_for("index")
    if not nxt.startswith("/"):
        nxt = url_for("index")
    user = verify_password(username, password)
    if not user:
        if not load_users():
            err = "No users configured. Put AUTH_USERS in .env or run: python set_user.py <username>"
        else:
            err = "Invalid username or password."
        return render_template("login.html", next=nxt, error=err), 401
    session["user"] = user
    session.permanent = True
    return redirect(nxt)


@app.get("/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


